export const getCountryInfo = (area) => countryData[area] || null;

export const getWikiUrl = (area) => {
  const info = getCountryInfo(area);
  const title = (info ? info.country : area).replace(/ /g, "_");
  return `https://en.wikipedia.org/wiki/${encodeURIComponent(title)}`;
};